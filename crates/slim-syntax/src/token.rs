use std::fmt;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Span {
    pub line: u32,
    pub col: u32,
}

#[derive(Clone, Debug, PartialEq)]
pub enum Tok {
    Name(String),
    Int(u64),
    Float(f64),
    Str(String),

    // keywords
    Def,
    Class,
    Trait,
    Impl,
    If,
    Elif,
    Else,
    While,
    For,
    In,
    Return,
    Yield,
    Try,
    Except,
    Finally,
    Raise,
    From,
    As,
    Pass,
    Break,
    Continue,
    And,
    Or,
    Not,
    Is,
    None,
    True,
    False,
    Global,
    Del,
    With,
    Assert,

    // punctuation
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Colon,
    /// `::` (turbofish: `list::<int>()`)
    ColonColon,
    Dot,
    Semi,
    Ellipsis,
    Assign,
    Arrow,
    LArrow,
    PlusPlus,
    Plus,
    Minus,
    Star,
    Slash,
    DSlash,
    Percent,
    DStar,
    Eq,
    Ne,
    Lt,
    Gt,
    Le,
    Ge,
    Shl,
    Shr,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    DSlashEq,
    PercentEq,
    Pipe,
    Amp,
    Caret,
    Tilde,

    Newline,
    Indent,
    Dedent,
    Eof,
}

impl Tok {
    pub fn keyword(s: &str) -> Option<Tok> {
        Some(match s {
            "def" => Tok::Def,
            "class" => Tok::Class,
            "trait" => Tok::Trait,
            "impl" => Tok::Impl,
            "if" => Tok::If,
            "elif" => Tok::Elif,
            "else" => Tok::Else,
            "while" => Tok::While,
            "for" => Tok::For,
            "in" => Tok::In,
            "return" => Tok::Return,
            "yield" => Tok::Yield,
            "try" => Tok::Try,
            "except" => Tok::Except,
            "finally" => Tok::Finally,
            "raise" => Tok::Raise,
            "from" => Tok::From,
            "as" => Tok::As,
            "pass" => Tok::Pass,
            "break" => Tok::Break,
            "continue" => Tok::Continue,
            "and" => Tok::And,
            "or" => Tok::Or,
            "not" => Tok::Not,
            "is" => Tok::Is,
            "None" => Tok::None,
            "True" => Tok::True,
            "False" => Tok::False,
            "global" => Tok::Global,
            "del" => Tok::Del,
            "with" => Tok::With,
            "assert" => Tok::Assert,
            _ => return None,
        })
    }
}

impl fmt::Display for Tok {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match self {
            Tok::Name(n) => return write!(f, "name `{n}`"),
            Tok::Int(i) => return write!(f, "integer `{i}`"),
            Tok::Float(x) => return write!(f, "float `{x}`"),
            Tok::Str(_) => "string literal",
            Tok::Def => "`def`",
            Tok::Class => "`class`",
            Tok::Trait => "`trait`",
            Tok::Impl => "`impl`",
            Tok::If => "`if`",
            Tok::Elif => "`elif`",
            Tok::Else => "`else`",
            Tok::While => "`while`",
            Tok::For => "`for`",
            Tok::In => "`in`",
            Tok::Return => "`return`",
            Tok::Yield => "`yield`",
            Tok::Try => "`try`",
            Tok::Except => "`except`",
            Tok::Finally => "`finally`",
            Tok::Raise => "`raise`",
            Tok::From => "`from`",
            Tok::As => "`as`",
            Tok::Pass => "`pass`",
            Tok::Break => "`break`",
            Tok::Continue => "`continue`",
            Tok::And => "`and`",
            Tok::Or => "`or`",
            Tok::Not => "`not`",
            Tok::Is => "`is`",
            Tok::None => "`None`",
            Tok::True => "`True`",
            Tok::False => "`False`",
            Tok::Global => "`global`",
            Tok::Del => "`del`",
            Tok::With => "`with`",
            Tok::Assert => "`assert`",
            Tok::LParen => "`(`",
            Tok::RParen => "`)`",
            Tok::LBracket => "`[`",
            Tok::RBracket => "`]`",
            Tok::LBrace => "`{`",
            Tok::RBrace => "`}`",
            Tok::Comma => "`,`",
            Tok::Colon => "`:`",
            Tok::ColonColon => "`::`",
            Tok::Dot => "`.`",
            Tok::Semi => "`;`",
            Tok::Ellipsis => "`...`",
            Tok::Assign => "`=`",
            Tok::Arrow => "`->`",
            Tok::LArrow => "`<-`",
            Tok::PlusPlus => "`++`",
            Tok::Plus => "`+`",
            Tok::Minus => "`-`",
            Tok::Star => "`*`",
            Tok::Slash => "`/`",
            Tok::DSlash => "`//`",
            Tok::Percent => "`%`",
            Tok::DStar => "`**`",
            Tok::Eq => "`==`",
            Tok::Ne => "`!=`",
            Tok::Lt => "`<`",
            Tok::Gt => "`>`",
            Tok::Le => "`<=`",
            Tok::Ge => "`>=`",
            Tok::Shl => "`<<`",
            Tok::Shr => "`>>`",
            Tok::PlusEq => "`+=`",
            Tok::MinusEq => "`-=`",
            Tok::StarEq => "`*=`",
            Tok::SlashEq => "`/=`",
            Tok::DSlashEq => "`//=`",
            Tok::PercentEq => "`%=`",
            Tok::Pipe => "`|`",
            Tok::Amp => "`&`",
            Tok::Caret => "`^`",
            Tok::Tilde => "`~`",
            Tok::Newline => "newline",
            Tok::Indent => "indent",
            Tok::Dedent => "dedent",
            Tok::Eof => "end of file",
        };
        f.write_str(s)
    }
}

#[derive(Clone, Debug)]
pub struct Token {
    pub tok: Tok,
    pub span: Span,
}
